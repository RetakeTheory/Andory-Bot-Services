#!/usr/bin/env node
"use strict";

const readline = require("node:readline");
const process = require("node:process");
const { setTimeout: delay } = require("node:timers/promises");

const VERSION = "1.0.1";
const CREDENTIAL_URL = "https://holo.rettheory.top";
const DEFAULT_REMOTE_URL = "wss://api.rettheory.top/ws/bot?channel=main&protocol=onebot11";
const DEFAULT_LOCAL_URLS = [
  "ws://127.0.0.1:3001",
  "ws://127.0.0.1:3000",
  "ws://127.0.0.1:6700",
  "ws://127.0.0.1:6701",
];

function printHelp() {
  console.log(`Andory OneBot Connector v${VERSION}

Usage:
  Andory-Connector [--onebot ws://127.0.0.1:3001] [--server wss://...] [--channel main]

The Andory credential is read from ANDORY_BOT_CREDENTIAL or entered securely at
startup. It is never written to disk. Do not pass credentials on the command
line because command lines may be visible to other processes.

Optional environment variables:
  ANDORY_BOT_CREDENTIAL  Credential issued at ${CREDENTIAL_URL}
  ANDORY_ONEBOT_WS_URL   Local OneBot forward-WebSocket URL(s), comma-separated
  ANDORY_ONEBOT_TOKEN    Optional local OneBot access token (query parameter)
  ANDORY_WS_URL          Andory reverse-WebSocket URL
  ANDORY_CHANNEL         Relay channel (default: main)

Without ANDORY_ONEBOT_WS_URL the connector probes common localhost OneBot ports.
Audit credentials may only be generated by an administrator account.`);
}

function parseArguments(argv) {
  const result = {};
  for (let index = 0; index < argv.length; index += 1) {
    const value = argv[index];
    if (value === "--help" || value === "-h") result.help = true;
    else if (value === "--version" || value === "-v") result.version = true;
    else if (value === "--onebot") result.onebot = requiredArgument(argv, ++index, value);
    else if (value === "--server") result.server = requiredArgument(argv, ++index, value);
    else if (value === "--channel") result.channel = requiredArgument(argv, ++index, value);
    else throw new Error(`Unknown option: ${value}`);
  }
  return result;
}

function requiredArgument(argv, index, option) {
  const value = argv[index];
  if (!value || value.startsWith("--")) throw new Error(`${option} requires a value`);
  return value;
}

async function readSecret(prompt) {
  if (!process.stdin.isTTY || typeof process.stdin.setRawMode !== "function") {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
    return new Promise((resolve) => rl.question(`${prompt}: `, (answer) => {
      rl.close();
      resolve(answer.trim());
    }));
  }

  process.stdout.write(`${prompt}: `);
  process.stdin.setRawMode(true);
  process.stdin.resume();
  return new Promise((resolve) => {
    let value = "";
    const finish = () => {
      process.stdin.setRawMode(false);
      process.stdin.off("data", onData);
      process.stdout.write("\n");
      resolve(value.trim());
    };
    const onData = (chunk) => {
      for (const byte of Buffer.from(chunk)) {
        if (byte === 3) {
          process.stdin.setRawMode(false);
          process.stdin.off("data", onData);
          process.stdout.write("\n");
          process.exit(130);
        }
        if (byte === 13 || byte === 10) return finish();
        if (byte === 8 || byte === 127) value = value.slice(0, -1);
        else if (byte >= 32) value += String.fromCharCode(byte);
      }
    };
    process.stdin.on("data", onData);
  });
}

function remoteUrl(base, credential, channel) {
  const url = new URL(base);
  if (url.protocol !== "wss:" && !(url.protocol === "ws:" && isLoopback(url.hostname))) {
    throw new Error("The Andory server must use wss:// (ws:// is allowed only for localhost)");
  }
  url.searchParams.set("channel", channel);
  url.searchParams.set("protocol", "onebot11");
  url.searchParams.set("token", credential);
  return url;
}

function localUrls(configured, accessToken) {
  const values = configured
    ? configured.split(",").map((value) => value.trim()).filter(Boolean)
    : DEFAULT_LOCAL_URLS;
  if (!values.length) throw new Error("No local OneBot WebSocket URL was configured");
  return values.map((value) => {
    const url = new URL(value);
    if ((url.protocol !== "ws:" && url.protocol !== "wss:") || !isLoopback(url.hostname)) {
      throw new Error(`Local OneBot URL must use localhost: ${value}`);
    }
    if (accessToken && !url.searchParams.has("access_token")) url.searchParams.set("access_token", accessToken);
    return url;
  });
}

function isLoopback(hostname) {
  return hostname === "localhost" || hostname === "127.0.0.1" || hostname === "::1" || hostname === "[::1]";
}

function displayUrl(url) {
  const safe = new URL(url);
  safe.searchParams.delete("token");
  safe.searchParams.delete("access_token");
  return safe.toString();
}

function openWebSocket(url, timeoutMs = 5000) {
  return new Promise((resolve, reject) => {
    const socket = new WebSocket(url);
    const timeout = setTimeout(() => fail(new Error(`Connection timed out: ${displayUrl(url)}`)), timeoutMs);
    const cleanup = () => {
      clearTimeout(timeout);
      socket.removeEventListener("open", opened);
      socket.removeEventListener("error", errored);
      socket.removeEventListener("close", closed);
    };
    const fail = (error) => {
      cleanup();
      try { socket.close(); } catch {}
      reject(error);
    };
    const opened = () => {
      cleanup();
      resolve(socket);
    };
    const errored = () => fail(new Error(`Unable to connect: ${displayUrl(url)}`));
    const closed = (event) => fail(new Error(`Connection closed (${event.code}): ${event.reason || displayUrl(url)}`));
    socket.addEventListener("open", opened, { once: true });
    socket.addEventListener("error", errored, { once: true });
    socket.addEventListener("close", closed, { once: true });
  });
}

async function openFirst(urls) {
  const attempts = urls.map((url) => openWebSocket(url, 3000)
    .then((socket) => ({ socket, url })));
  try {
    const selected = await Promise.any(attempts);
    for (const attempt of attempts) {
      attempt.then(({ socket }) => {
        if (socket !== selected.socket) socket.close(1000, "another local endpoint was selected");
      }).catch(() => {});
    }
    return selected;
  } catch {
    throw new Error(`No local OneBot forward WebSocket was found (${urls.map(displayUrl).join(", ")})`);
  }
}

function bridge(remote, local) {
  return new Promise((resolve) => {
    let finished = false;
    let forwarded = 0;
    const heartbeat = setInterval(() => {
      const uptime = Math.floor(process.uptime());
      console.log(`[running] uptime=${uptime}s forwarded=${forwarded}`);
    }, 30000);
    const forward = (target) => (event) => {
      if (target.readyState !== WebSocket.OPEN) return;
      target.send(event.data);
      forwarded += 1;
    };
    const remoteToLocal = forward(local);
    const localToRemote = forward(remote);
    const finish = (source, event) => {
      if (finished) return;
      finished = true;
      clearInterval(heartbeat);
      remote.removeEventListener("message", remoteToLocal);
      local.removeEventListener("message", localToRemote);
      try { remote.close(); } catch {}
      try { local.close(); } catch {}
      const code = event && typeof event.code === "number" ? event.code : 0;
      const reason = event && event.reason ? ` ${event.reason}` : "";
      resolve(`${source} disconnected (${code})${reason}`);
    };
    remote.addEventListener("message", remoteToLocal);
    local.addEventListener("message", localToRemote);
    remote.addEventListener("close", (event) => finish("Andory", event), { once: true });
    local.addEventListener("close", (event) => finish("OneBot", event), { once: true });
    remote.addEventListener("error", (event) => finish("Andory", event), { once: true });
    local.addEventListener("error", (event) => finish("OneBot", event), { once: true });
  });
}

async function run(options) {
  console.log(`Andory OneBot Connector v${VERSION}`);
  console.log(`Bot credentials: ${CREDENTIAL_URL}`);
  console.log("Audit credentials are restricted to administrator accounts.");
  console.log("Credentials remain in memory only. Press Ctrl+C to stop.\n");

  // BOT_WS_TOKEN belongs to the private game-data adapter. Never treat that
  // deployment secret as a local OneBot credential: stale .env values would
  // otherwise silently override the credential the user intended to enter.
  const credential = process.env.ANDORY_BOT_CREDENTIAL || await readSecret("Andory Bot credential");
  if (!credential) throw new Error("Andory Bot credential is required");
  const channel = options.channel || process.env.ANDORY_CHANNEL || "main";
  if (!/^[A-Za-z0-9_-]{1,64}$/.test(channel)) throw new Error("Invalid channel");
  const remote = remoteUrl(options.server || process.env.ANDORY_WS_URL || DEFAULT_REMOTE_URL, credential, channel);
  const locals = localUrls(options.onebot || process.env.ANDORY_ONEBOT_WS_URL || "", process.env.ANDORY_ONEBOT_TOKEN || "");

  let retryMs = 1000;
  while (true) {
    console.log(`[connecting] Andory ${displayUrl(remote)}`);
    console.log(`[connecting] local OneBot ${locals.map(displayUrl).join(", ")}`);
    try {
      const [remoteSocket, localResult] = await Promise.all([openWebSocket(remote, 10000), openFirst(locals)]);
      retryMs = 1000;
      console.log(`[running] connected to ${displayUrl(localResult.url)}\n`);
      const reason = await bridge(remoteSocket, localResult.socket);
      console.warn(`[reconnect] ${reason}`);
    } catch (error) {
      console.warn(`[reconnect] ${error instanceof Error ? error.message : String(error)}`);
    }
    console.log(`[reconnect] retrying in ${Math.ceil(retryMs / 1000)}s`);
    await delay(retryMs);
    retryMs = Math.min(retryMs * 2, 30000);
  }
}

async function main() {
  try {
    const options = parseArguments(process.argv.slice(2));
    if (options.help) return printHelp();
    if (options.version) return console.log(VERSION);
    await run(options);
  } catch (error) {
    console.error(`[stopped] ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  }
}

main();
