import { createGzip } from "node:zlib";
import { createWriteStream } from "node:fs";
import { copyFile, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { pipeline } from "node:stream/promises";
import { createHash } from "node:crypto";
import postject from "postject";
import tarStream from "tar-stream";

const execFileAsync = promisify(execFile);
const { inject } = postject;
const { pack: createTarPack } = tarStream;
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "launcher", "andory-onebot-connector.cjs");
const LICENSE = resolve(ROOT, "..", "LICENSE");
const DIST = join(ROOT, "release");
const CACHE = join(ROOT, ".release-cache");
const VERSION = "1.0.1";
const NODE_VERSION = process.version.slice(1);
const SEA_FUSE = "NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2";
const targets = [
  { id: "linux-x64", archive: `node-v${NODE_VERSION}-linux-x64.tar.xz`, node: "bin/node" },
  { id: "linux-arm64", archive: `node-v${NODE_VERSION}-linux-arm64.tar.xz`, node: "bin/node" },
  { id: "macos-x64", archive: `node-v${NODE_VERSION}-darwin-x64.tar.gz`, node: "bin/node" },
  { id: "macos-arm64", archive: `node-v${NODE_VERSION}-darwin-arm64.tar.gz`, node: "bin/node" },
];

await rm(DIST, { recursive: true, force: true });
await mkdir(DIST, { recursive: true });
await mkdir(CACHE, { recursive: true });

const source = await readFile(SOURCE);
await buildWindowsSea();
for (const target of targets) await buildPortable(target, source);
await writeChecksums();
console.log(`Built Andory Connector v${VERSION} with Node ${NODE_VERSION} in ${DIST}`);

async function buildWindowsSea() {
  if (process.platform !== "win32") {
    console.warn("Skipping Windows SEA: run this build on Windows to produce the .exe");
    return;
  }
  const seaConfig = join(CACHE, "sea-config.json");
  const seaBlob = join(CACHE, "andory-connector.blob");
  await writeFile(seaConfig, JSON.stringify({
    main: SOURCE,
    output: seaBlob,
    disableExperimentalSEAWarning: true,
    useSnapshot: false,
    useCodeCache: false,
  }, null, 2));
  await execFileAsync(process.execPath, ["--experimental-sea-config", seaConfig], { cwd: ROOT });
  const output = join(DIST, `Andory-Connector-v${VERSION}-windows-x64.exe`);
  await copyFile(process.execPath, output);
  await inject(output, "NODE_SEA_BLOB", await readFile(seaBlob), { sentinelFuse: SEA_FUSE });
  console.log(`built ${output}`);
}

async function buildPortable(target, launcherSource) {
  const archivePath = join(CACHE, target.archive);
  const extractedRoot = join(CACHE, target.archive.replace(/\.(tar\.xz|tar\.gz)$/u, ""));
  const runtimeRoot = join(extractedRoot, target.archive.replace(/\.(tar\.xz|tar\.gz)$/u, ""));
  const runtime = join(runtimeRoot, ...target.node.split("/"));
  if (!(await fileExists(runtime))) {
    if (!(await fileExists(archivePath))) await download(`https://nodejs.org/dist/v${NODE_VERSION}/${target.archive}`, archivePath);
    await rm(extractedRoot, { recursive: true, force: true });
    await mkdir(extractedRoot, { recursive: true });
    const runtimeMember = `${target.archive.replace(/\.(tar\.xz|tar\.gz)$/u, "")}/${target.node}`;
    await execFileAsync("tar", ["-xf", archivePath, "-C", extractedRoot, runtimeMember]);
  }

  const prefix = `Andory-Connector-v${VERSION}-${target.id}`;
  const readme = Buffer.from(`Andory OneBot Connector v${VERSION}\n\nRun:\n  ./run-andory.sh\n\nThe package includes the official Node.js ${NODE_VERSION} runtime, so Node does not need to be installed.\nThe launcher asks only for the Andory Bot credential. Get it from https://holo.rettheory.top.\nAudit credentials may only be generated by administrator accounts.\n\nOptional local OneBot endpoint:\n  ANDORY_ONEBOT_WS_URL=ws://127.0.0.1:3001 ./run-andory.sh\n\nNo credential, session, MasterData, game asset, font or cache is included.\n`);
  const shell = Buffer.from("#!/bin/sh\nset -eu\nHERE=$(CDPATH= cd -- \"$(dirname -- \"$0\")\" && pwd)\nexec \"$HERE/node\" \"$HERE/andory-onebot-connector.cjs\" \"$@\"\n");
  const files = [
    { name: `${prefix}/node`, data: await readFile(runtime), mode: 0o755 },
    { name: `${prefix}/andory-onebot-connector.cjs`, data: launcherSource, mode: 0o644 },
    { name: `${prefix}/run-andory.sh`, data: shell, mode: 0o755 },
    { name: `${prefix}/README.txt`, data: readme, mode: 0o644 },
    { name: `${prefix}/LICENSE`, data: await readFile(LICENSE), mode: 0o644 },
  ];
  const output = join(DIST, `${prefix}.tar.gz`);
  await createTarGz(output, files);
  console.log(`built ${output}`);
}

async function createTarGz(output, files) {
  const archive = createTarPack();
  const writing = pipeline(archive, createGzip({ level: 9 }), createWriteStream(output));
  for (const file of files) {
    await new Promise((resolveEntry, rejectEntry) => archive.entry({
      name: file.name,
      mode: file.mode,
      size: file.data.length,
      mtime: new Date(0),
      uid: 0,
      gid: 0,
    }, file.data, (error) => error ? rejectEntry(error) : resolveEntry()));
  }
  archive.finalize();
  await writing;
}

async function download(url, output) {
  console.log(`downloading ${url}`);
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Download failed (${response.status}): ${url}`);
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, Buffer.from(await response.arrayBuffer()));
}

async function writeChecksums() {
  const { readdir } = await import("node:fs/promises");
  const names = (await readdir(DIST)).filter((name) => name !== "SHA256SUMS.txt").sort();
  const lines = [];
  for (const name of names) {
    const digest = createHash("sha256").update(await readFile(join(DIST, name))).digest("hex");
    lines.push(`${digest}  ${name}`);
  }
  await writeFile(join(DIST, "SHA256SUMS.txt"), `${lines.join("\n")}\n`);
}

async function fileExists(path) {
  try {
    await readFile(path);
    return true;
  } catch (error) {
    if (error && error.code === "ENOENT") return false;
    throw error;
  }
}
